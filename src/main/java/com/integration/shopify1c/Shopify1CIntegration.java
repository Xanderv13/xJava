package com.integration.shopify1c;

import com.integration.shopify1c.config.Config;
import com.integration.shopify1c.service.SyncService;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.TimeUnit;

/**
 * ??????? ????? ?????????? ??? ?????????? Shopify ? 1?
 */
public class Shopify1CIntegration {
    private static final Logger logger = LoggerFactory.getLogger(Shopify1CIntegration.class);
    private final SyncService syncService;
    private ScheduledExecutorService scheduler;
    
    public Shopify1CIntegration() {
        this.syncService = new SyncService();
        this.scheduler = Executors.newScheduledThreadPool(1);
    }
    
    /**
     * ?????? ????????????? ???? ???
     */
    public void runOnce() {
        logger.info("?????? ??????? ?????????????...");
        syncService.syncAll();
    }
    
    /**
     * ?????? ????????????? ?????????????
     */
    public void startScheduledSync() {
        int intervalMinutes = Config.getSyncIntervalMinutes();
        logger.info("?????? ????????????? ????????????? ? ?????????? {} ?????", intervalMinutes);
        
        scheduler.scheduleAtFixedRate(
            () -> {
                try {
                    syncService.syncAll();
                } catch (Exception e) {
                    logger.error("?????? ??? ????????????? ?????????????", e);
                }
            },
            0,
            intervalMinutes,
            TimeUnit.MINUTES
        );
    }
    
    /**
     * ????????? ?????????????
     */
    public void stop() {
        if (scheduler != null && !scheduler.isShutdown()) {
            scheduler.shutdown();
            try {
                if (!scheduler.awaitTermination(60, TimeUnit.SECONDS)) {
                    scheduler.shutdownNow();
                }
            } catch (InterruptedException e) {
                scheduler.shutdownNow();
                Thread.currentThread().interrupt();
            }
        }
    }
    
    public static void main(String[] args) {
        logger.info("?????? ?????????? Shopify-1C...");
        
        // ???????? ????????????
        if (Config.getShopifyAccessToken() == null || Config.getShopifyShopName() == null) {
            logger.error("?? ????????? ????????? ??????????? ? Shopify. ????????? ????????????.");
            System.exit(1);
        }
        
        if (Config.getOneCBaseUrl() == null) {
            logger.error("?? ????????? ????????? ??????????? ? 1?. ????????? ????????????.");
            System.exit(1);
        }
        
        Shopify1CIntegration integration = new Shopify1CIntegration();
        
        // ????????? ?????????? ??????????
        Runtime.getRuntime().addShutdownHook(new Thread(() -> {
            logger.info("?????????? ?????? ??????????...");
            integration.stop();
        }));
        
        // ????????? ?????????????
        if (args.length > 0 && "once".equals(args[0])) {
            // ??????? ?????????????
            integration.runOnce();
        } else {
            // ????????????? ?????????????
            integration.startScheduledSync();
            
            // ?????? ?????????? ??????????
            try {
                Thread.sleep(Long.MAX_VALUE);
            } catch (InterruptedException e) {
                logger.info("?????????? ????????");
            }
        }
    }
}

package com.integration.shopify1c.service;

import com.integration.shopify1c.client.OneCClient;
import com.integration.shopify1c.client.ShopifyClient;
import com.integration.shopify1c.config.Config;
import com.integration.shopify1c.model.Order;
import com.integration.shopify1c.model.Product;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.util.Date;
import java.util.List;

/**
 * ?????? ????????????? ?????? ????? Shopify ? 1?
 */
public class SyncService {
    private static final Logger logger = LoggerFactory.getLogger(SyncService.class);
    private final ShopifyClient shopifyClient;
    private final OneCClient oneCClient;
    private Date lastSyncDate;
    
    public SyncService() {
        this.shopifyClient = new ShopifyClient();
        this.oneCClient = new OneCClient();
        this.lastSyncDate = new Date(System.currentTimeMillis() - 24 * 60 * 60 * 1000); // ????????? 24 ????
    }
    
    /**
     * ????????????? ??????? ?? Shopify ? 1?
     */
    public void syncProducts() {
        if (!Config.isSyncProductsEnabled()) {
            logger.info("????????????? ??????? ?????????");
            return;
        }
        
        try {
            logger.info("?????? ????????????? ???????...");
            List<Product> products = shopifyClient.getProducts();
            
            int successCount = 0;
            int errorCount = 0;
            
            for (Product product : products) {
                try {
                    if (oneCClient.sendProduct(product)) {
                        successCount++;
                    } else {
                        errorCount++;
                    }
                } catch (IOException e) {
                    logger.error("?????? ??? ???????? ?????? {} ? 1?", product.getSku(), e);
                    errorCount++;
                }
            }
            
            logger.info("????????????? ??????? ?????????. ???????: {}, ??????: {}", successCount, errorCount);
        } catch (IOException e) {
            logger.error("?????? ??? ????????????? ???????", e);
        }
    }
    
    /**
     * ????????????? ??????? ?? Shopify ? 1?
     */
    public void syncOrders() {
        if (!Config.isSyncOrdersEnabled()) {
            logger.info("????????????? ??????? ?????????");
            return;
        }
        
        try {
            logger.info("?????? ????????????? ???????...");
            List<Order> orders = shopifyClient.getOrders(lastSyncDate);
            
            int successCount = 0;
            int errorCount = 0;
            
            for (Order order : orders) {
                try {
                    if (oneCClient.sendOrder(order)) {
                        successCount++;
                        // ????????? ???? ????????? ?????????????
                        if (order.getCreatedAt() != null && 
                            (lastSyncDate == null || order.getCreatedAt().after(lastSyncDate))) {
                            lastSyncDate = order.getCreatedAt();
                        }
                    } else {
                        errorCount++;
                    }
                } catch (IOException e) {
                    logger.error("?????? ??? ???????? ?????? {} ? 1?", order.getOrderNumber(), e);
                    errorCount++;
                }
            }
            
            logger.info("????????????? ??????? ?????????. ???????: {}, ??????: {}", successCount, errorCount);
        } catch (IOException e) {
            logger.error("?????? ??? ????????????? ???????", e);
        }
    }
    
    /**
     * ?????? ????????????? (?????? + ??????)
     */
    public void syncAll() {
        logger.info("=== ?????? ?????? ????????????? ===");
        syncProducts();
        syncOrders();
        logger.info("=== ????????????? ????????? ===");
    }
    
    public Date getLastSyncDate() {
        return lastSyncDate;
    }
}
